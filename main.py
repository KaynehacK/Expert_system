def ask_question(question_text, options):
    """
    Выводит вопрос на экран и ожидает корректного ввода от пользователя.
    options представляет собой список кортежей: (буква_выбора, текст_варианта, словарь_обновления_факторов)
    """
    print(f"\n{question_text}")
    for letter, text, _ in options:
        print(f"  [{letter}] {text}")

    while True:
        choice = input("Введите ваш выбор (А, Б или В): ").strip().upper()
        for letter, _, factor_updates in options:
            if choice == letter:
                return factor_updates
        print("Ошибка ввода. Пожалуйста, введите одну из предложенных букв.")


def match_methods(current_state):
    """
    Ищет в базе знаний подходящий метод на основе собранных факторов.
    """
    matching_results = []
    for method in METHODS_DATABASE:
        is_match = True
        for factor_key, required_value in method["rules"].items():
            if current_state.get(factor_key) != required_value:
                is_match = False
                break
        if is_match:
            matching_results.append(method)
    return matching_results


